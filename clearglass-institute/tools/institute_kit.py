def check_claims(register: dict) -> list[str]:
    claims = register.get("claims")
    if not isinstance(claims, list) or not claims:
        return ["legal_claims: 'claims' must be a non-empty list"]
    out: list[str] = []
    seen: list[str] = []
    for index, claim in enumerate(claims):
        if not isinstance(claim, dict):
            out.append(f"legal_claims: entry {index} must be an object")
            continue
        cid = claim.get("id")
        label = cid if isinstance(cid, str) else f"entry {index}"
        if not isinstance(cid, str) or not _CLAIM_ID.match(cid):
            out.append(f"legal_claims: {label} needs an id like L-01")
        elif cid in seen:
            out.append(f"legal_claims: {cid} appears more than once")
        else:
            seen.append(cid)
        unknown = sorted(set(claim) - _CLAIM_KEYS)
        if unknown:
            out.append(f"legal_claims: {label} has unexpected keys {unknown}")
        for key in ("topic", "claim", "authority"):
            if not isinstance(claim.get(key), str) or not claim[key].strip():
                out.append(f"legal_claims: {label} needs a non-empty {key}")
        status = claim.get("status")
        if status not in CLAIM_STATUSES:
            out.append(f"legal_claims: {label} status must be one of {sorted(CLAIM_STATUSES)}")
        if _parse_date(claim.get("checked")) is None:
            out.append(f"legal_claims: {label} needs a checked date as YYYY-MM-DD")
        sources = claim.get("sources")
        if not isinstance(sources, list):
            out.append(f"legal_claims: {label} sources must be a list")
            sources = []
        for source in sources:
            url = source.get("url") if isinstance(source, dict) else None
            title = source.get("title") if isinstance(source, dict) else None
            if not isinstance(title, str) or not title.strip():
                out.append(f"legal_claims: {label} has a source without a title")
            if not isinstance(url, str) or not url.startswith("https://"):
                out.append(f"legal_claims: {label} has a source without an https URL")
        if status == "UNVERIFIED":
            if not isinstance(claim.get("action"), str) or not claim["action"].strip():
                out.append(f"legal_claims: {label} is UNVERIFIED and needs an action")
        elif status in CLAIM_STATUSES and not sources:
            out.append(f"legal_claims: {label} is {status} and needs at least one source")
    if seen != sorted(seen):
        out.append("legal_claims: entries must be in id order")
    return out


def stale_claims(register: dict, today: dt.date) -> list[str]:
    out: list[str] = []
    for claim in register.get("claims", []):
        checked = _parse_date(claim.get("checked")) if isinstance(claim, dict) else None
        if checked and (today - checked).days > STALE_AFTER_DAYS:
            out.append(
                f"legal_claims: {claim.get('id')} was last checked {claim['checked']}; "
                f"recheck it (older than {STALE_AFTER_DAYS} days)"
            )
    return out


def _claim_index(register: dict) -> dict[str, dict]:
    return {
        claim["id"]: claim
        for claim in register.get("claims", [])
        if isinstance(claim, dict) and isinstance(claim.get("id"), str)
    }


# ------------------------------------------------------------------------ notices


def entity_statement(status: dict) -> str:
    """One or two sentences on what the Institute is, taken from the record."""
    entity = status["entity"]
    name = entity["proposed_name"]
    if not _met(status, "certificate_of_incorporation"):
        return (
            f"{name} is a proposed organization. "
            "It is not yet incorporated and is not a registered charity."
        )
    number = entity["corporation_number"]
    lead = f"{name} is an Ontario not-for-profit corporation (Ontario Corporation Number {number})."
    if _charity_registered(status):
        return lead + " It is a registered charity."
    return lead + " It is not a registered charity and cannot issue official donation receipts."


def doc_notice(status: dict) -> str:
    return f"{NOTICE_PREFIX}{entity_statement(status)} {NOTICE_TAIL}"


def page_notice(status: dict) -> str:
    statement = entity_statement(status)
    if not _met(status, "certificate_of_incorporation"):
        return statement + " It does not accept donations, payments or memberships."
    if _charity_registered(status):
        return statement
    return statement + " Donations are not tax-receiptable."


# ----------------------------------------------------------------------- rendering


def _state_cell(record: dict) -> str:
    return f"Done {record['date']}" if record["met"] else "Not yet"


def next_step(status: dict) -> str | None:
    for key in RUNBOOK_ORDER:
        if not _met(status, key):
            return key
    return None


def render_status_md(status: dict, register: dict) -> str:
    entity = status["entity"]
    records = _records(status)
    done = sum(1 for key, _ in CORE_GATES if records[key]["met"])
    lines = [
        "# ClearGlass Institute: formation status",
        "",
        doc_notice(status),
        "",
        f"Record as of {status['as_of']}. Source: `data/status.json`.",
        "",
        "## The six tests",
        "",
        "The founding kit calls the Institute real only when all six are true.",
        "",
        "| # | Test | State | Evidence |",
        "|---|---|---|---|",
    ]
    for number, (key, label) in enumerate(CORE_GATES, start=1):
        record = records[key]
        lines.append(f"| {number} | {label} | {_state_cell(record)} | {record['evidence'] or ''} |")
    verdict = (
        "All six tests are met."
        if done == len(CORE_GATES)
        else f"{done} of {len(CORE_GATES)} tests met. Treat the kit as a plan, not an organization."
    )
    lines += [
        "",
        f"**Result: {verdict}**",
        "",
        "## Other tracked steps",
        "",
        "| Step | State | Evidence |",
        "|---|---|---|",
    ]
    for key, label in MILESTONES:
        record = records[key]
        lines.append(f"| {label} | {_state_cell(record)} | {record['evidence'] or ''} |")
    charity = status["charity"]
    charity_state = f"Registered {charity['date']}" if charity["registered"] else "Not registered"
    site = status["public_site"]
    site_state = f"Live at {site['url']}" if site["live"] else "Not live"
    lines += [
        "",
        "## Entity",
        "",
        f"- Name: {entity['proposed_name']}",
        f"- Statute: {entity['statute']}",
        f"- Registered office: {entity['registered_office_municipality']}",
        f"- Ontario Corporation Number: {entity['corporation_number'] or 'none'}",
        f"- Incorporation date: {entity['incorporation_date'] or 'none'}",
        f"- Financial year end: {entity['financial_year_end'] or 'not chosen'}",
        f"- Charity registration: {charity_state}",
        f"- Public site: {site_state}",
        f"- Partners with a written agreement on record: {len(status['named_partners'])}",
        "",
        "## Next step",
        "",
    ]
    step = next_step(status)
    if step is None:
        lines.append("Every tracked step is recorded as done.")
    else:
        lines.append(f"{STEP_LABELS[step]}. See `operations/RUNBOOK.md`.")
    incorporated = _parse_date(entity["incorporation_date"])
    lines += ["", "## Compliance dates", ""]
    if incorporated is None:
        lines.append(
            "None yet. Dates run from the incorporation date. To model them, run "
            "`python3 clearglass-institute/tools/institute_kit.py calendar "
            "--incorporated YYYY-MM-DD --fye MM-DD`."
        )
    else:
        year_end = _parse_year_end(entity["financial_year_end"])
        lines += ["| Date | Obligation | Rule | Rule verification |", "|---|---|---|---|"]
        for item in compliance_dates(incorporated, year_end, register):
            lines.append(
                f"| {item['date']} | {item['obligation']} | {item['rule']} | {item['verification']} |"
            )
        if year_end is None:
            lines += ["", "Year-end dates are missing because no financial year end is recorded."]
    lines += ["", GENERATED_FOOTER, ""]
    return "\n".join(lines)


def render_legal_md(status: dict, register: dict) -> str:
    claims = [c for c in register.get("claims", []) if isinstance(c, dict)]
    counts = {name: sum(1 for c in claims if c.get("status") == name) for name in CLAIM_STATUSES}
    lines = [
        "# ClearGlass Institute: legal source register",
        "",
        doc_notice(status),
        "",
        (
            "Every legal rule the kit relies on is listed here with its sources and how far it "
            "was verified. Documents cite rules by id, for example `[L-01]`."
        ),
        "",
        str(register.get("method", "")).strip(),
        "",
        "## Verification levels",
        "",
        "| Level | Meaning | Rules |",
        "|---|---|---|",
    ]
    for name, meaning in CLAIM_STATUSES.items():
        lines.append(f"| {name} | {meaning} | {counts[name]} |")
    topics: list[str] = []
    for claim in claims:
        if claim.get("topic") not in topics:
            topics.append(claim.get("topic"))
    for topic in topics:
        lines += [
            "",
            f"## {topic}",
            "",
            "| Id | Rule | Authority | Level | Checked | Sources |",
            "|---|---|---|---|---|---|",
        ]
        for claim in (c for c in claims if c.get("topic") == topic):
            links = (
                " ".join(
                    f"[{n}]({source['url']})"
                    for n, source in enumerate(claim.get("sources", []), start=1)
                )
                or "none"
            )
            lines.append(
                f"| {claim['id']} | {claim['claim']} | {claim['authority']} | "
                f"{claim['status']} | {claim['checked']} | {links} |"
            )
        for claim in (c for c in claims if c.get("topic") == topic):
            if claim.get("note"):
                lines += ["", f"- {claim['id']} note: {claim['note']}"]
            if claim.get("action"):
                lines += ["", f"- {claim['id']} action: {claim['action']}"]
    lines += ["", "## Source list", ""]
    for claim in claims:
        for n, source in enumerate(claim.get("sources", []), start=1):
            lines.append(f"- {claim['id']} [{n}] {source['title']}: <{source['url']}>")
    lines += ["", GENERATED_FOOTER, ""]
    return "\n".join(lines)


def render_page_status(status: dict) -> str:
    records = _records(status)
    items = []
    for key, label in CORE_GATES:
        record = records[key]
        state = f"done {record['date']}" if record["met"] else "not yet"
        items.append(f"    <li>{html.escape(label)}: {state}</li>")
    partners = status["named_partners"]
    block = [
        '  <ul class="status">',
        *items,
        "  </ul>",
        f'  <p class="meta">Record as of {html.escape(status["as_of"])}.</p>',
    ]
    if partners:
        names = ", ".join(html.escape(p["name"]) for p in partners)
        block.append(f'  <p class="meta">Organizations with a written agreement: {names}.</p>')
    return "\n".join(block)


def _replace_block(text: str, name: str, body: str) -> str | None:
    start, end = f"<!-- cgi:{name}:start -->", f"<!-- cgi:{name}:end -->"
    if text.count(start) != 1 or text.count(end) != 1 or text.index(start) > text.index(end):
        return None
    head, rest = text.split(start, 1)
    _, tail = rest.split(end, 1)
    return f"{head}{start}\n{body}\n{end}{tail}"


def _doc_files(root: Path) -> list[Path]:
    return sorted(p for p in root.rglob("*.md") if p.name not in GENERATED_DOCS or p.parent != root)


def _page_files(root: Path) -> list[Path]:
    site = root / "site"
    return sorted(site.glob("*.html")) if site.is_dir() else []


def expected_files(root: Path, status: dict, register: dict) -> tuple[dict[Path, str], list[str]]:
    """Return the content every managed file should have, plus structural findings."""
    expected: dict[Path, str] = {
        root / "STATUS.md": render_status_md(status, register),
        root / "LEGAL_VERIFICATION.md": render_legal_md(status, register),
    }
    findings: list[str] = []
    notice = doc_notice(status)
    for path in _doc_files(root):
        rel = path.relative_to(root).as_posix()
        lines = path.read_text(encoding="utf-8").split("\n")
        hits = [i for i, line in enumerate(lines) if line.startswith(NOTICE_PREFIX)]
        if len(hits) != 1:
            findings.append(
                f"{rel}: needs exactly one line starting with '{NOTICE_PREFIX.strip()}' "
                f"(found {len(hits)})"
            )
            continue
        lines[hits[0]] = notice
        expected[path] = "\n".join(lines)
    for path in _page_files(root):
        rel = path.relative_to(root).as_posix()
        text = path.read_text(encoding="utf-8")
        notice_html = f'  <p class="notice" role="note">{html.escape(page_notice(status))}</p>'
        for name, body in (("notice", notice_html), ("status", render_page_status(status))):
            replaced = _replace_block(text, name, body)
            if replaced is None:
                findings.append(f"{rel}: needs one '<!-- cgi:{name}:start -->' / ':end -->' pair")
            else:
                text = replaced
        expected[path] = text
    return expected, findings


