class KitError(Exception):
    """A data file is missing or cannot be read."""


# --------------------------------------------------------------------------- loading


def _load_json(path: Path) -> dict:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise KitError(f"{path.name}: file is missing") from exc
    except json.JSONDecodeError as exc:
        raise KitError(f"{path.name}: not valid JSON ({exc})") from exc
    if not isinstance(data, dict):
        raise KitError(f"{path.name}: top level must be an object")
    return data


def load_status(root: Path) -> dict:
    return _load_json(root / "data" / "status.json")


def load_claims(root: Path) -> dict:
    return _load_json(root / "data" / "legal_claims.json")


def _parse_date(value: object) -> dt.date | None:
    if not isinstance(value, str) or not re.fullmatch(r"\d{4}-\d{2}-\d{2}", value):
        return None
    try:
        return dt.date.fromisoformat(value)
    except ValueError:
        return None


def _parse_year_end(value: object) -> tuple[int, int] | None:
    if not isinstance(value, str) or not re.fullmatch(r"\d{2}-\d{2}", value):
        return None
    month, day = int(value[:2]), int(value[3:])
    try:
        dt.date(2001, month, day)  # a non-leap year, so 02-29 is refused
    except ValueError:
        return None
    return month, day


def _records(status: dict) -> dict[str, dict]:
    merged: dict[str, dict] = {}
    for group in ("gates", "milestones"):
        section = status.get(group)
        if isinstance(section, dict):
            for key, record in section.items():
                if isinstance(record, dict):
                    merged[key] = record
    return merged


def _met(status: dict, key: str) -> bool:
    return _records(status).get(key, {}).get("met") is True


def _charity_registered(status: dict) -> bool:
    charity = status.get("charity")
    return isinstance(charity, dict) and charity.get("registered") is True


# ------------------------------------------------------------------- status checks


def _check_record(name: str, record: object, as_of: dt.date | None) -> list[str]:
    if not isinstance(record, dict):
        return [f"status: {name} must be an object"]
    out: list[str] = []
    if set(record) != _RECORD_KEYS:
        out.append(f"status: {name} must have exactly the keys {sorted(_RECORD_KEYS)}")
        return out
    met, date, evidence = record["met"], record["date"], record["evidence"]
    if not isinstance(met, bool):
        return [f"status: {name}.met must be true or false"]
    if not met:
        if date is not None or evidence is not None:
            out.append(f"status: {name} is not met, so its date and evidence must be null")
        return out
    parsed = _parse_date(date)
    if parsed is None:
        out.append(f"status: {name} is met and needs a date as YYYY-MM-DD")
    elif as_of and parsed > as_of:
        out.append(f"status: {name} is dated after as_of")
    if not isinstance(evidence, str) or not evidence.strip():
        out.append(f"status: {name} is met and needs evidence (where the record is kept)")
    elif _CONTACT_DETAIL.search(evidence):
        out.append(
            f"status: {name}.evidence looks like it holds contact details; "
            "point to the record instead, this repository is public"
        )
    return out


def check_status(status: dict) -> list[str]:
    out: list[str] = []
    if set(status) != _TOP_KEYS:
        extra = sorted(set(status) - _TOP_KEYS)
        missing = sorted(_TOP_KEYS - set(status))
        out.append(f"status: unexpected keys {extra}, missing keys {missing}")
        return out
    if status["schema_version"] != 1:
        out.append("status: schema_version must be 1")
    as_of = _parse_date(status["as_of"])
    if as_of is None:
        out.append("status: as_of must be a date as YYYY-MM-DD")

    for group, expected in (("gates", CORE_GATES), ("milestones", MILESTONES)):
        section = status[group]
        wanted = [key for key, _ in expected]
        if not isinstance(section, dict) or sorted(section) != sorted(wanted):
            out.append(f"status: {group} must have exactly the keys {wanted}")
            continue
        for key in wanted:
            out.extend(_check_record(f"{group}.{key}", section[key], as_of))
    if out:
        return out

    for step, needs in REQUIRES.items():
        if _met(status, step):
            for need in needs:
                if not _met(status, need):
                    out.append(f"status: {step} is recorded as done but {need} is not")

    entity = status["entity"]
    if not isinstance(entity, dict) or set(entity) != _ENTITY_KEYS:
        out.append(f"status: entity must have exactly the keys {sorted(_ENTITY_KEYS)}")
    else:
        for key in ("proposed_name", "statute", "registered_office_municipality"):
            if not isinstance(entity[key], str) or not entity[key].strip():
                out.append(f"status: entity.{key} must be a non-empty string")
        certified = _met(status, "certificate_of_incorporation")
        number, inc_date = entity["corporation_number"], entity["incorporation_date"]
        if certified:
            if not isinstance(number, str) or not number.strip():
                out.append("status: the certificate is recorded, so corporation_number is needed")
            parsed = _parse_date(inc_date)
            if parsed is None:
                out.append("status: the certificate is recorded, so incorporation_date is needed")
            elif as_of and parsed > as_of:
                out.append("status: incorporation_date is after as_of")
        elif number is not None or inc_date is not None:
            out.append(
                "status: corporation_number and incorporation_date must be null "
                "until the certificate is recorded"
            )
        year_end = entity["financial_year_end"]
        if year_end is not None and _parse_year_end(year_end) is None:
            out.append("status: financial_year_end must be null or MM-DD")

    out.extend(_check_charity(status, as_of))
    out.extend(_check_public_site(status))
    out.extend(_check_partners(status, as_of))
    return out


def _check_charity(status: dict, as_of: dt.date | None) -> list[str]:
    charity = status["charity"]
    if not isinstance(charity, dict) or set(charity) != {"registered", "date", "evidence"}:
        return ["status: charity must have exactly the keys ['date', 'evidence', 'registered']"]
    record = {
        "met": charity["registered"],
        "date": charity["date"],
        "evidence": charity["evidence"],
    }
    out = [msg.replace(".met", ".registered") for msg in _check_record("charity", record, as_of)]
    if charity["registered"] is True:
        for need in ("certificate_of_incorporation", "cra_business_number"):
            if not _met(status, need):
                out.append(f"status: charity is recorded as registered but {need} is not done")
    return out


def _check_public_site(status: dict) -> list[str]:
    site = status["public_site"]
    if not isinstance(site, dict) or set(site) != {"live", "url"}:
        return ["status: public_site must have exactly the keys ['live', 'url']"]
    out: list[str] = []
    live, url = site["live"], site["url"]
    if not isinstance(live, bool):
        return ["status: public_site.live must be true or false"]
    host = ""
    if url is not None:
        parsed = urlparse(url) if isinstance(url, str) else None
        if parsed is None or parsed.scheme != "https" or not parsed.hostname:
            out.append("status: public_site.url must be null or an https URL")
        else:
            host = parsed.hostname.lower()
    if live and not host:
        out.append("status: public_site is live, so it needs an https URL")
    if host == INC_DOMAIN or host.endswith("." + INC_DOMAIN):
        out.append(
            "status: public_site.url is on the ClearGlass Inc. domain; "
            "the Institute's site must be on its own domain"
        )
    if _met(status, "public_charity_disclaimer") and not live:
        out.append(
            "status: public_charity_disclaimer is recorded as done but public_site is not live"
        )
    return out


def _check_partners(status: dict, as_of: dt.date | None) -> list[str]:
    partners = status["named_partners"]
    if not isinstance(partners, list):
        return ["status: named_partners must be a list"]
    out: list[str] = []
    for index, partner in enumerate(partners):
        label = f"named_partners[{index}]"
        if not isinstance(partner, dict) or set(partner) != {"name", "agreement_date", "evidence"}:
            out.append(f"status: {label} needs exactly name, agreement_date and evidence")
            continue
        if not isinstance(partner["name"], str) or not partner["name"].strip():
            out.append(f"status: {label}.name must be a non-empty string")
        record = {"met": True, "date": partner["agreement_date"], "evidence": partner["evidence"]}
        out.extend(_check_record(label, record, as_of))
    return out


