def visible_sentences(page: str) -> list[str]:
    metas = re.findall(r'(?is)<meta\b[^>]*\bcontent="([^"]*)"', page)
    text = re.sub(r"(?is)<(script|style)\b.*?</\1>", " ", page)
    text = re.sub(r"(?s)<!--.*?-->", " ", text)
    boundary = " "
    text = re.sub(
        r"(?i)</(?:p|li|h[1-6]|td|th|tr|div|section|dt|dd|title|figcaption|blockquote|footer|"
        r"header|a)>|<br\s*/?>",
        boundary,
        text,
    )
    text = re.sub(r"<[^>]+>", " ", text)
    text = html.unescape(text)
    parts = re.split(boundary + r"|(?<=[.!?])\s+", text)
    parts += [html.unescape(meta) for meta in metas]
    return [" ".join(part.split()) for part in parts if part.strip()]


def _rule_off(status: dict, switch: str | None) -> bool:
    if switch is None:
        return False
    if switch == "charity":
        return _charity_registered(status)
    if switch == "named_partners":
        return bool(status["named_partners"])
    return _met(status, switch)


def scan_public_text(status: dict, rel: str, page: str) -> list[str]:
    out: list[str] = []
    for sentence in visible_sentences(page):
        for rule, switch, trigger, message in PUBLIC_RULES:
            if _rule_off(status, switch) or not trigger.search(sentence):
                continue
            if _HEDGE.search(_NOT_A_HEDGE.sub(" ", sentence)):
                continue
            out.append(f'{rel}: [{rule}] {message}: "{sentence[:120]}"')
    return out


# ----------------------------------------------------------------------- calendar


def add_months(day: dt.date, months: int) -> dt.date:
    index = day.month - 1 + months
    year, month = day.year + index // 12, index % 12 + 1
    return dt.date(year, month, min(day.day, _calendar.monthrange(year, month)[1]))


def first_year_end(incorporated: dt.date, year_end: tuple[int, int]) -> dt.date:
    month, day = year_end
    candidate = dt.date(incorporated.year, month, day)
    return candidate if candidate > incorporated else dt.date(incorporated.year + 1, month, day)


def compliance_dates(
    incorporated: dt.date, year_end: tuple[int, int] | None, register: dict
) -> list[dict[str, str]]:
    index = _claim_index(register)

    def item(day: dt.date, obligation: str, *rules: str) -> dict[str, str]:
        levels = sorted({index.get(rule, {}).get("status", "MISSING") for rule in rules})
        return {
            "date": day.isoformat(),
            "obligation": obligation,
            "rule": ", ".join(f"[{rule}]" for rule in rules) or "none",
            "verification": ", ".join(levels) or "not a rule",
        }

    sixty = incorporated + dt.timedelta(days=60)
    items = [
        item(sixty, "File the initial return with the Ontario Business Registry", "L-12"),
        item(
            sixty,
            "Pass the Institute's own by-laws, or the Ministry's standard by-laws apply",
            "L-18",
        ),
        item(
            add_months(incorporated, 18),
            "Latest date for the first annual meeting of members",
            "L-15",
        ),
    ]
    if year_end is not None:
        end = first_year_end(incorporated, year_end)
        due = add_months(end, 6)
        items += [
            item(end, "First financial year ends"),
            item(due, "File the Ontario annual return", "L-13"),
            item(due, "File the T2 return, and the T1044 if its tests are met", "L-25", "L-24"),
            item(
                due, "Planning date: annual meeting held and financial statements presented", "L-16"
            ),
        ]
    return sorted(items, key=lambda entry: (entry["date"], entry["obligation"]))


# ------------------------------------------------------------------------- driver


def check(root: Path, today: dt.date | None = None) -> tuple[list[str], list[str]]:
    """Return (findings, warnings). Any finding fails the check."""
    try:
        status, register = load_status(root), load_claims(root)
    except KitError as exc:
        return [str(exc)], []
    findings = check_status(status) + check_claims(register)
    if findings:
        return findings, []
    known = _claim_index(register)
    expected, structural = expected_files(root, status, register)
    findings += structural
    for path, content in expected.items():
        rel = path.relative_to(root).as_posix()
        if not path.exists():
            findings.append(f"{rel}: missing; run 'institute_kit.py render'")
        elif path.read_text(encoding="utf-8") != content:
            findings.append(f"{rel}: out of date with data/; run 'institute_kit.py render'")
    for path in _doc_files(root) + _page_files(root):
        rel = path.relative_to(root).as_posix()
        text = path.read_text(encoding="utf-8")
        for ref in sorted(set(_CLAIM_REF.findall(text)) - set(known)):
            findings.append(f"{rel}: cites [{ref}], which is not in data/legal_claims.json")
    for path in _page_files(root):
        rel = path.relative_to(root).as_posix()
        findings += scan_public_text(status, rel, path.read_text(encoding="utf-8"))
    warnings = stale_claims(register, today or dt.date.today())
    return findings, warnings


def render(root: Path) -> list[str]:
    status, register = load_status(root), load_claims(root)
    problems = check_status(status) + check_claims(register)
    if problems:
        raise KitError("fix the data files first:\n  " + "\n  ".join(problems))
    expected, _ = expected_files(root, status, register)
    changed: list[str] = []
    for path, content in expected.items():
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            path.write_text(content, encoding="utf-8")
            changed.append(path.relative_to(root).as_posix())
    return changed


def _cmd_check(args: argparse.Namespace) -> int:
    today = _parse_date(args.today) if args.today else None
    if args.today and today is None:
        print("--today must be YYYY-MM-DD", file=sys.stderr)
        return 2
    findings, warnings = check(args.root, today)
    for warning in warnings:
        print(f"warning: {warning}", file=sys.stderr)
    if args.strict:
        findings = findings + warnings
    for finding in findings:
        print(finding)
    if findings:
        print(f"\n{len(findings)} finding(s). The kit does not pass.")
        return 1
    print(f"Institute kit check passed ({len(warnings)} warning(s)).")
    return 0


def _cmd_render(args: argparse.Namespace) -> int:
    try:
        changed = render(args.root)
    except KitError as exc:
        print(exc, file=sys.stderr)
        return 1
    print("\n".join(f"updated {name}" for name in changed) or "nothing to update")
    return 0


def _cmd_status(args: argparse.Namespace) -> int:
    try:
        status = load_status(args.root)
    except KitError as exc:
        print(exc, file=sys.stderr)
        return 1
    problems = check_status(status)
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    records = _records(status)
    done = 0
    for key, label in CORE_GATES:
        met = records[key]["met"]
        done += met
        print(f"[{'x' if met else ' '}] {label}")
    print(f"\n{done} of {len(CORE_GATES)} tests met as of {status['as_of']}.")
    step = next_step(status)
    print(f"Next step: {STEP_LABELS[step]}." if step else "Every tracked step is done.")
    return 0


def _cmd_calendar(args: argparse.Namespace) -> int:
    try:
        status, register = load_status(args.root), load_claims(args.root)
    except KitError as exc:
        print(exc, file=sys.stderr)
        return 1
    entity = status.get("entity", {})
    raw_date = args.incorporated or entity.get("incorporation_date")
    incorporated = _parse_date(raw_date)
    if incorporated is None:
        print(
            "No incorporation date is recorded. Pass --incorporated YYYY-MM-DD to model one.",
            file=sys.stderr,
        )
        return 2
    raw_end = args.fye or entity.get("financial_year_end")
    year_end = _parse_year_end(raw_end) if raw_end else None
    if raw_end and year_end is None:
        print("--fye must be MM-DD", file=sys.stderr)
        return 2
    items = compliance_dates(incorporated, year_end, register)
    if args.json:
        print(json.dumps(items, indent=2))
        return 0
    modelled = "" if entity.get("incorporation_date") else " (modelled, not a recorded date)"
    print(f"Incorporation date {incorporated.isoformat()}{modelled}")
    for entry in items:
        print(f"{entry['date']}  {entry['obligation']}  {entry['rule']}  ({entry['verification']})")
    print("\nPlanning dates only. Confirm each rule in LEGAL_VERIFICATION.md before relying on it.")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--root", type=Path, default=KIT_ROOT, help=argparse.SUPPRESS)
    sub = parser.add_subparsers(dest="command", required=True)
    p_check = sub.add_parser("check", help="fail on any unsupported claim or stale file")
    p_check.add_argument("--today", help="date to measure source age from (YYYY-MM-DD)")
    p_check.add_argument("--strict", action="store_true", help="treat warnings as findings")
    p_check.set_defaults(func=_cmd_check)
    sub.add_parser("render", help="regenerate notices and generated files").set_defaults(
        func=_cmd_render
    )
    sub.add_parser("status", help="print the six tests").set_defaults(func=_cmd_status)
    p_cal = sub.add_parser("calendar", help="compute compliance dates")
    p_cal.add_argument("--incorporated", help="incorporation date (YYYY-MM-DD)")
    p_cal.add_argument("--fye", help="financial year end (MM-DD)")
    p_cal.add_argument("--json", action="store_true")
    p_cal.set_defaults(func=_cmd_calendar)
    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
